"""Stateful synthetic match engine.

The engine plays possession *sequences*. A sequence belongs to one team, starts where
the previous one ended (mirrored into the new team's attacking frame), and advances
the ball step by step with passes and carries until it ends in a shot, a turnover, a
foul, a corner or the ball going out. Scheduled goals from the scenario force a
build-up sequence that ends in a goal at the scripted minute; every other shot is
saved, blocked or off target, so the final score is exactly the scenario's story
while every statistic around it is generated by the simulation.

Determinism: one `random.Random(seed)` instance drives everything, so the same
scenario and seed always produce byte-identical event lists.
"""
from __future__ import annotations

import random
from dataclasses import dataclass, field

from app.models.core import EventType, MatchEvent, Player
from app.simulator.rosters import TEAMS
from app.simulator.scenarios import Scenario, ScheduledGoal

PITCH_L, PITCH_W = 105.0, 68.0
HALF_SECONDS = 45 * 60


@dataclass
class _State:
    t: int = 0
    period: int = 1
    seq_no: int = 0
    event_no: int = 0
    score: dict[str, int] = field(default_factory=lambda: {"north-city": 0, "south-united": 0})
    on_pitch: dict[str, list[str]] = field(default_factory=dict)
    subs_done: set[tuple[int, str, str]] = field(default_factory=set)
    goals_done: set[int] = field(default_factory=set)
    possession: str = "north-city"
    x: float = 52.5
    y: float = 34.0
    last_pass: tuple[str, str] | None = None  # (passer_id, receiver_id)
    prev_pass: tuple[str, str] | None = None


class MatchEngine:
    def __init__(self, scenario: Scenario, seed: int | None = None):
        self.scenario = scenario
        self.seed = scenario.seed if seed is None else seed
        self.rng = random.Random(self.seed)
        self.home = scenario.home
        self.away = scenario.away
        self.players: dict[str, Player] = {p.id: p for tid in (self.home, self.away) for p in TEAMS[tid].players}
        self.events: list[MatchEvent] = []
        self.s = _State()
        self.half_end = HALF_SECONDS
        self.s.on_pitch = {tid: [p.id for p in TEAMS[tid].players if p.starter] for tid in (self.home, self.away)}

    # ----------------------------------------------------------------- helpers
    def _opp(self, team: str) -> str:
        return self.away if team == self.home else self.home

    def _minute(self) -> float:
        return self.s.t / 60.0

    def _display(self, team: str, x: float, y: float) -> tuple[float, float]:
        if team == self.home:
            return round(x, 1), round(y, 1)
        return round(PITCH_L - x, 1), round(PITCH_W - y, 1)

    def _emit(self, type_: EventType, team: str | None = None, player: Player | None = None, *,
              related: Player | None = None, outcome: str | None = None,
              x: float | None = None, y: float | None = None, end_x: float | None = None, end_y: float | None = None,
              xg: float | None = None, progressive: bool = False, final_third_entry: bool = False,
              box_entry: bool = False, key_pass: bool = False, description: str = "") -> MatchEvent:
        self.s.event_no += 1
        px = py = pex = pey = None
        if team and x is not None and y is not None:
            px, py = self._display(team, x, y)
        if team and end_x is not None and end_y is not None:
            pex, pey = self._display(team, end_x, end_y)
        ev = MatchEvent(
            id=f"E{self.s.event_no:04d}", seq=self.s.event_no, t=self.s.t, minute=self.s.t // 60, second=self.s.t % 60,
            period=self.s.period, type=type_, team=team,
            player_id=player.id if player else None, player_name=player.name if player else None,
            related_player_id=related.id if related else None, related_player_name=related.name if related else None,
            outcome=outcome, x=None if x is None else round(x, 1), y=None if y is None else round(y, 1),
            end_x=None if end_x is None else round(end_x, 1), end_y=None if end_y is None else round(end_y, 1),
            pitch_x=px, pitch_y=py, pitch_end_x=pex, pitch_end_y=pey, xg=xg, progressive=progressive,
            final_third_entry=final_third_entry, box_entry=box_entry, key_pass=key_pass,
            sequence_id=self.s.seq_no, score_home=self.s.score[self.home], score_away=self.s.score[self.away],
            description=description,
        )
        self.events.append(ev)
        return ev

    def _advance(self, seconds: int) -> None:
        self.s.t = min(self.s.t + seconds, self.half_end)

    def _pick_player(self, team: str, x: float, *, exclude: str | None = None, prefer: str | None = None,
                     weight_key: str = "passing") -> Player:
        """Weighted choice of an on-pitch outfield player, by proximity of their role to the ball zone."""
        zone = x / PITCH_L  # 0 own goal .. 1 opponent goal
        pos_center = {"GK": 0.05, "DF": 0.28, "MF": 0.52, "FW": 0.78}
        cands, weights = [], []
        for pid in self.s.on_pitch[team]:
            p = self.players[pid]
            if pid == exclude:
                continue
            if p.position == "GK" and zone > 0.2:
                continue
            dist = abs(pos_center[p.position] - zone)
            w = max(0.05, 1.0 - dist * 1.8) * (0.5 + getattr(p, weight_key)) * (0.6 + p.workrate * 0.8)
            w *= self.scenario.player_boost.get(pid, 1.0)
            if prefer and pid == prefer:
                w *= 6.0
            cands.append(p)
            weights.append(w)
        return self.rng.choices(cands, weights=weights, k=1)[0]

    @staticmethod
    def _xg(x: float, y: float) -> float:
        """Simple location model: distance and angle to goal centre (105, 34)."""
        dx = max(0.5, PITCH_L - x)
        dy = y - PITCH_W / 2
        dist = (dx * dx + dy * dy) ** 0.5
        angle = abs(dy) / dx
        base = 0.9 * (1.0 / (1.0 + (dist / 7.5) ** 1.9))
        return round(max(0.02, min(0.85, base * (1.0 - 0.35 * min(1.0, angle)))), 2)

    # --------------------------------------------------------------- scheduling
    def _pending_goal(self) -> ScheduledGoal | None:
        m = self._minute()
        for i, g in enumerate(self.scenario.goals):
            if i in self.s.goals_done:
                continue
            if g.minute - 0.25 <= m:
                return g
        return None

    def _apply_subs(self) -> None:
        m = self._minute()
        for sub in self.scenario.subs:
            key = (sub.minute, sub.team, sub.player_out)
            if key in self.s.subs_done or m < sub.minute:
                continue
            lineup = self.s.on_pitch[sub.team]
            if sub.player_out in lineup and sub.player_in not in lineup:
                lineup[lineup.index(sub.player_out)] = sub.player_in
                pin, pout = self.players[sub.player_in], self.players[sub.player_out]
                self._emit(EventType.SUBSTITUTION, sub.team, pin, related=pout,
                           description=f"{pin.name} replaces {pout.name}")
            self.s.subs_done.add(key)

    # ----------------------------------------------------------------- sequence
    def _start_sequence(self, team: str, x: float, y: float) -> None:
        self.s.seq_no += 1
        self.s.possession = team
        self.s.x, self.s.y = x, y
        self.s.last_pass = None
        self.s.prev_pass = None

    def _turnover(self, from_team: str, x: float, y: float, kind: EventType, description: str) -> None:
        """Opponent wins the ball at (x, y) in from_team's frame. Starts a new sequence for them."""
        to_team = self._opp(from_team)
        ox, oy = PITCH_L - x, PITCH_W - y  # mirror into the winner's frame
        self.s.seq_no += 1
        self.s.possession = to_team
        winner = self._pick_player(to_team, ox, weight_key="defending")
        self._emit(kind, to_team, winner, outcome="won", x=ox, y=oy, description=f"{winner.name} {description}")
        self.s.x, self.s.y = ox, oy
        self.s.last_pass = None
        self.s.prev_pass = None

    def _play_sequence(self, forced_goal: ScheduledGoal | None = None) -> None:
        team = self.s.possession
        opp = self._opp(team)
        hi, ai = self.scenario.intensity(self._minute())
        intensity = hi if team == self.home else ai
        defence = ai if team == self.home else hi
        x, y = self.s.x, self.s.y
        steps = self.rng.randint(2, 4 + int(intensity * 6))
        if forced_goal:
            steps = max(steps, 5)
        carrier = self._pick_player(team, x, prefer=forced_goal.assist if forced_goal and forced_goal.assist else None)
        was_final_third = x >= 70

        for step in range(steps):
            self._apply_subs()
            last_step = step == steps - 1
            # Decide the action for this step
            if forced_goal and last_step:
                # The goal. Route the ball through the scripted assist provider when possible.
                scorer = self.players[forced_goal.scorer]
                if scorer.id not in self.s.on_pitch[team]:
                    scorer = carrier
                assist_p = self.players[forced_goal.assist] if forced_goal.assist else None
                if assist_p and assist_p.id in self.s.on_pitch[team] and assist_p.id != scorer.id and carrier.id != assist_p.id:
                    ax, ay = min(96.0, x + self.rng.uniform(4, 9)), max(6.0, min(62.0, y + self.rng.uniform(-10, 10)))
                    self._emit(EventType.PASS, team, carrier, related=assist_p, outcome="complete", x=x, y=y, end_x=ax, end_y=ay,
                               progressive=ax - x >= 8, final_third_entry=(x < 70 <= ax), box_entry=(ax >= 88.5 and 13.8 <= ay <= 54.2),
                               description=f"{carrier.name} to {assist_p.name}")
                    self.s.prev_pass, self.s.last_pass = self.s.last_pass, (carrier.id, assist_p.id)
                    carrier, x, y = assist_p, ax, ay
                    self._advance(self.rng.randint(2, 4))
                sx = min(103.0, max(88.0, x + self.rng.uniform(3, 10)))
                sy = 34 + self.rng.uniform(-9, 9)
                if carrier.id != scorer.id:
                    self._emit(EventType.PASS, team, carrier, related=scorer, outcome="complete", x=x, y=y, end_x=sx, end_y=sy,
                               progressive=sx - x >= 8, final_third_entry=(x < 70 <= sx), box_entry=(sx >= 88.5 and 13.8 <= sy <= 54.2),
                               key_pass=True, description=f"{carrier.name} plays in {scorer.name}")
                    self.s.prev_pass, self.s.last_pass = self.s.last_pass, (carrier.id, scorer.id)
                    self._advance(self.rng.randint(2, 4))
                xg = self._xg(sx, sy)
                self._emit(EventType.SHOT, team, scorer, outcome="goal", x=sx, y=sy, xg=xg, description=f"{scorer.name} shoots")
                self.s.score[team] += 1
                assist = self.players[self.s.last_pass[0]] if self.s.last_pass and self.s.last_pass[1] == scorer.id else None
                self._emit(EventType.GOAL, team, scorer, related=assist, outcome="goal", x=sx, y=sy, xg=xg,
                           description=f"GOAL {scorer.name}" + (f" (assist {assist.name})" if assist else "") + (f". {forced_goal.note}" if forced_goal.note else ""))
                self._advance(self.rng.randint(40, 75))  # celebration + restart
                self.s.seq_no += 1
                self.s.possession = opp
                self.s.x, self.s.y = 52.5, 34.0
                self.s.last_pass = None
                return

            in_box_zone = x >= 86
            shot_p = 0.0 if forced_goal else (0.04 + 0.15 * intensity) if in_box_zone else (0.015 * intensity if x >= 76 else 0.0)
            if not forced_goal and self.rng.random() < shot_p and carrier.position != "GK":
                sx, sy = x + self.rng.uniform(0, 4), max(8.0, min(60.0, y + self.rng.uniform(-6, 6)))
                xg = self._xg(sx, sy)
                r = self.rng.random()
                outcome = "on_target" if r < 0.38 else ("blocked" if r < 0.6 else "off_target")
                desc = {"on_target": "shot saved", "blocked": "shot blocked", "off_target": "shot off target"}[outcome]
                self._emit(EventType.SHOT, team, carrier, outcome=outcome, x=sx, y=sy, xg=xg, description=f"{carrier.name} {desc}")
                if self.s.last_pass and self.s.last_pass[1] == carrier.id:
                    # mark the assisting pass as a key pass
                    for ev in reversed(self.events[-6:]):
                        if ev.type == EventType.PASS and ev.player_id == self.s.last_pass[0] and ev.related_player_id == carrier.id:
                            ev.key_pass = True
                            break
                self._advance(self.rng.randint(3, 7))
                if outcome in ("blocked", "on_target") and self.rng.random() < 0.45:
                    self._emit(EventType.CORNER, team, carrier, x=104.0, y=0.5 if sy < 34 else 67.5, description=f"Corner for {TEAMS[team].short}")
                    self._advance(self.rng.randint(20, 35))
                    cx, cy = 98.0, 34 + self.rng.uniform(-8, 8)
                    self.s.x, self.s.y = cx, cy
                    x, y = cx, cy
                    carrier = self._pick_player(team, x)
                    continue
                # goalkeeper restart for the opponent
                self.s.seq_no += 1
                self.s.possession = opp
                self.s.x, self.s.y = 8.0, 34.0
                self.s.last_pass = None
                return

            # foul?
            if not forced_goal and self.rng.random() < 0.012 + 0.012 * defence:
                fouler = self._pick_player(opp, PITCH_L - x, weight_key="defending")
                ox, oy = PITCH_L - x, PITCH_W - y
                self._emit(EventType.FOUL, opp, fouler, related=carrier, outcome="conceded", x=ox, y=oy, description=f"{fouler.name} fouls {carrier.name}")
                if self.rng.random() < 0.18:
                    self._emit(EventType.CARD, opp, fouler, outcome="yellow", x=ox, y=oy, description=f"Yellow card {fouler.name}")
                self._advance(self.rng.randint(15, 30))
                self.s.last_pass = None
                x, y = min(x, 100.0), y
                carrier = self._pick_player(team, x)
                continue

            # pass or carry
            carry = self.rng.random() < 0.28 + 0.1 * carrier.progression
            if carry:
                gain = self.rng.uniform(2, 6 + 8 * carrier.progression * intensity)
                nx, ny = min(103.0, x + gain), max(2.0, min(66.0, y + self.rng.uniform(-6, 6)))
                self._emit(EventType.CARRY, team, carrier, outcome="complete", x=x, y=y, end_x=nx, end_y=ny,
                           progressive=nx - x >= 8, final_third_entry=(x < 70 <= nx), box_entry=(nx >= 88.5 and 13.8 <= ny <= 54.2),
                           description=f"{carrier.name} carries forward")
                x, y = nx, ny
                self._advance(self.rng.randint(3, 6))
                # possible tackle
                if not forced_goal and self.rng.random() < 0.06 + 0.12 * defence * (x / PITCH_L):
                    self._turnover(team, x, y, EventType.TACKLE, "wins the tackle")
                    return
                continue

            receiver = self._pick_player(team, min(103.0, x + 10 * intensity), exclude=carrier.id)
            forward = self.rng.random() < 0.45 + 0.4 * intensity
            gain = self.rng.uniform(4, 10 + 14 * carrier.progression) if forward else self.rng.uniform(-10, 3)
            if forced_goal:
                gain = max(gain, 6.0)
            nx, ny = max(3.0, min(103.0, x + gain)), max(2.0, min(66.0, y + self.rng.uniform(-14, 14)))
            # completion probability
            diff = 0.04 + (0.0026 * max(0.0, gain)) + 0.08 * defence * (nx / PITCH_L)
            p_complete = min(0.97, max(0.55, carrier.passing + 0.12 - diff))
            if forced_goal:
                p_complete = 1.0
            if self.rng.random() < p_complete:
                self._emit(EventType.PASS, team, carrier, related=receiver, outcome="complete", x=x, y=y, end_x=nx, end_y=ny,
                           progressive=gain >= 8 and nx >= 40, final_third_entry=(x < 70 <= nx), box_entry=(nx >= 88.5 and 13.8 <= ny <= 54.2),
                           description=f"{carrier.name} to {receiver.name}")
                self.s.prev_pass, self.s.last_pass = self.s.last_pass, (carrier.id, receiver.id)
                carrier = receiver
                x, y = nx, ny
                self._advance(self.rng.randint(2, 5))
            else:
                r = self.rng.random()
                self._emit(EventType.PASS, team, carrier, related=receiver, outcome="incomplete", x=x, y=y, end_x=nx, end_y=ny,
                           description=f"{carrier.name} misplaces a pass")
                self._advance(self.rng.randint(2, 4))
                if r < 0.55:
                    self._turnover(team, nx, ny, EventType.INTERCEPTION, "intercepts")
                else:
                    self._turnover(team, nx, ny, EventType.RECOVERY, "recovers the loose ball")
                return
            if not was_final_third and x >= 70:
                was_final_third = True

        # sequence fizzles out: opponent recovers a loose ball or the ball goes out
        self._advance(self.rng.randint(2, 6))
        self._turnover(team, x, y, EventType.RECOVERY, "recovers possession")

    # ---------------------------------------------------------------------- run
    def run(self) -> list[MatchEvent]:
        s = self.s
        kicker = self._pick_player(self.home, 52.5)
        self._emit(EventType.KICKOFF, self.home, kicker, x=52.5, y=34.0, description="Kick-off")
        self._start_sequence(self.home, 52.5, 34.0)
        self._advance(2)
        self._play_half(end_t=HALF_SECONDS)
        s.t = HALF_SECONDS
        s.possession = self.away
        self._emit(EventType.HALFTIME, description="Half-time")
        s.period = 2
        self.half_end = 2 * HALF_SECONDS
        kicker = self._pick_player(self.away, 52.5)
        self._emit(EventType.KICKOFF, self.away, kicker, x=52.5, y=34.0, description="Second half kick-off")
        self._start_sequence(self.away, 52.5, 34.0)
        self._advance(2)
        self._play_half(end_t=2 * HALF_SECONDS)
        s.t = 2 * HALF_SECONDS
        self._apply_subs()
        self._emit(EventType.FULLTIME, description="Full-time")
        return self.events

    def _play_half(self, end_t: int) -> None:
        s = self.s
        guard = 0
        while s.t < end_t and guard < 5000:
            guard += 1
            self._apply_subs()
            pending = self._pending_goal()
            if pending and s.t < end_t - 45:
                if s.possession != pending.team:
                    self._turnover(s.possession, s.x, s.y, EventType.RECOVERY, "wins the ball back")
                # bring the ball to a realistic build-up start
                s.x = max(s.x, 35.0)
                idx = self.scenario.goals.index(pending)
                s.goals_done.add(idx)
                self._play_sequence(forced_goal=pending)
                continue
            self._play_sequence()
        # clamp any overshoot
        if s.t > end_t:
            s.t = end_t


def simulate(scenario: Scenario, seed: int | None = None) -> list[MatchEvent]:
    return MatchEngine(scenario, seed).run()
